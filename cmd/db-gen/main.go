const modulePath = "github.com/ahmedbaig/go-backend-db-handler"

func main() {
	name := flag.String("name", "db-handler", "config name; reads <name>-db.json from CONFIG_DIR")
	out := flag.String("out", "models", "output directory for generated models")
	only := flag.String("database", "", "generate only this database")
	typesDir := flag.String("types", "types", "output directory for the shared types module")
	typesOnly := flag.Bool("types-only", false, "skip introspection; regenerate registry and types from existing models")
	flag.Parse()

	var err error
	if *typesOnly {
		err = writeRegistry(*out)
	} else {
		err = run(*name, *out, *only)
	}
	if err == nil {
		err = writeTypes(*out, *typesDir)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "db-gen:", err)
		os.Exit(1)
	}
}

var identRe = regexp.MustCompile(`[^a-z0-9_]`)

func pkgName(database string) string {
	p := identRe.ReplaceAllString(strings.ToLower(database), "_")
	if p == "" || (p[0] >= '0' && p[0] <= '9') {
		p = "db_" + p
	}
	return p
}

func run(name, out, only string) error {
	cfg, err := config.Load(name+"-db", appconfig.DB{})
	if err != nil {
		return err
	}
	if len(cfg.Connections) == 0 {
		return fmt.Errorf("no connections in %s-db config", name)
	}
	log := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelWarn}))
	ctx := context.Background()

	done := map[string]bool{}
	for _, c := range cfg.Connections {
		if done[c.Database] || (only != "" && c.Database != only) {
			continue
		}
		done[c.Database] = true
		c.Instance = ""
		pool, err := connections.Open(ctx, appconfig.DB{Connections: []appconfig.Connection{c}}, log)
		if err != nil {
			return err
		}
		gdb, _ := pool.Get(c.Database, "")
		pkg := pkgName(c.Database)
		dir := filepath.Join(out, pkg)
		if err := os.RemoveAll(filepath.Join(dir)); err != nil {
			return err
		}
		g := gen.NewGenerator(gen.Config{
			OutPath:           filepath.Join(os.TempDir(), "db-gen-query-"+pkg),
			ModelPkgPath:      dir,
			FieldNullable:     true,
			FieldCoverable:    false,
			FieldWithIndexTag: true,
			FieldWithTypeTag:  true,
		})
		g.UseDB(gdb)
		g.GenerateAllTable()
		g.Execute()
		_ = pool.Close()
		marker := fmt.Sprintf("// Code generated by db-gen. DO NOT EDIT.\n\npackage %s\n\nconst Database = %q\n", pkg, c.Database)
		if err := os.WriteFile(filepath.Join(dir, "database_gen.go"), []byte(marker), 0o644); err != nil {
			return err
		}
		fmt.Printf("generated %s -> %s\n", c.Database, dir)
	}
	return writeRegistry(out)
}

type entry struct {
	database string
	service  string
	pkg      string
	typ      string
}

func writeRegistry(out string) error {
	dirs, err := os.ReadDir(out)
	if err != nil {
		return err
	}
	var entries []entry
	pkgs := map[string]bool{}
	for _, d := range dirs {
		if !d.IsDir() {
			continue
		}
		es, err := scanPackage(filepath.Join(out, d.Name()), d.Name())
		if err != nil {
			return err
		}
		if len(es) > 0 {
			pkgs[d.Name()] = true
			entries = append(entries, es...)
		}
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].database != entries[j].database {
			return entries[i].database < entries[j].database
		}
		return entries[i].service < entries[j].service
	})
	return os.WriteFile(filepath.Join(out, "registry_gen.go"), render(entries, pkgs), 0o644)
}

func scanPackage(dir, pkg string) ([]entry, error) {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	var out []entry
	database := pkg
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		af, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range af.Decls {
			if gd, ok := decl.(*ast.GenDecl); ok && gd.Tok == token.CONST {
				for _, spec := range gd.Specs {
					vs := spec.(*ast.ValueSpec)
					for i, n := range vs.Names {
						if n.Name == "Database" && i < len(vs.Values) {
							if lit, ok := vs.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
								database, _ = strconv.Unquote(lit.Value)
							}
						}
					}
				}
			}
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Name.Name != "TableName" || fn.Recv == nil || len(fn.Recv.List) != 1 || fn.Body == nil {
				continue
			}
			typ := recvType(fn.Recv.List[0].Type)
			table := returnedString(fn.Body)
			if typ == "" || table == "" {
				continue
			}
			out = append(out, entry{database: pkg, service: table, pkg: pkg, typ: typ})
		}
	}
	for i := range out {
		out[i].database = database
	}
	return out, nil
}

func recvType(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return recvType(t.X)
	case *ast.Ident:
		return t.Name
	}
	return ""
}

func returnedString(b *ast.BlockStmt) string {
	for _, s := range b.List {
		r, ok := s.(*ast.ReturnStmt)
		if !ok || len(r.Results) != 1 {
			continue
		}
		switch v := r.Results[0].(type) {
		case *ast.BasicLit:
			if v.Kind == token.STRING {
				s, _ := strconv.Unquote(v.Value)
				return s
			}
		case *ast.Ident:
			return constLookup(v)
		}
	}
	return ""
}

func constLookup(id *ast.Ident) string {
	if id.Obj == nil || id.Obj.Decl == nil {
		return ""
	}
	vs, ok := id.Obj.Decl.(*ast.ValueSpec)
	if !ok {
		return ""
	}
	for i, n := range vs.Names {
		if n.Name == id.Name && i < len(vs.Values) {
			if lit, ok := vs.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
				s, _ := strconv.Unquote(lit.Value)
				return s
			}
		}
	}
	return ""
}

func render(entries []entry, pkgs map[string]bool) []byte {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// Code generated by db-gen. DO NOT EDIT.\n\npackage models\n\nimport (\n")
	w("\t%q\n", modulePath+"/internal/registry")
	names := make([]string, 0, len(pkgs))
	for p := range pkgs {
		names = append(names, p)
	}
	sort.Strings(names)
	for _, p := range names {
		w("\t%q\n", modulePath+"/models/"+p)
	}
	w(")\n\nfunc Register(r *registry.Registry) {\n")
	for _, e := range entries {
		w("\tr.Add(%q, %q, &%s.%s{})\n", e.database, e.service, e.pkg, e.typ)
	}
	w("}\n\nfunc All() map[string][]any {\n\treturn map[string][]any{\n")
	byDB := map[string][]entry{}
	var dbs []string
	for _, e := range entries {
		if _, ok := byDB[e.database]; !ok {
			dbs = append(dbs, e.database)
		}
		byDB[e.database] = append(byDB[e.database], e)
	}
	for _, d := range dbs {
		w("\t\t%q: {", d)
		for i, e := range byDB[d] {
			if i > 0 {
				w(", ")
			}
			w("&%s.%s{}", e.pkg, e.typ)
		}
		w("},\n")
	}
	w("\t}\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes()
	}
	return src
}
